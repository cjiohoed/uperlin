import palette
import effects

# ============================================================
# ВЫБОР ЭФФЕКТА И ПАЛИТРЫ
# ============================================================
EFFECT = effects.fill_flame_octaves
PAL    = palette.FIRE
# ============================================================

# ============================================================
# Количество светодиодов в ленте
# ============================================================
NUM_LEDS     = 150

# ============================================================
# Номер GPIO-пина ESP32, к которому подключена линия данных ленты

# Какие пины подходят:
# - Любой свободный GPIO кроме пинов 6–11 (они заняты flash-памятью)
# - Пины 34–39 не подойдут — они только входы (input-only), не могут выдавать сигнал
# - Пины 0, 2, 12, 15 — работают, но могут быть заняты при загрузке (если на них что-то висит — плата может не стартовать)
# - Разумные значения: 5, 13, 14, 16, 17, 18, 19, 21, 22, 23, 25, 26, 27, 32, 33
# ============================================================
DATA_PIN     = 5

# ============================================================
# Масштаб шума вдоль ленты — насколько «сжатой» будет картинка по координате X

# Малое X_SCALE (10–30) — каждый LED «отстоит» друг от друга в шуме на малое расстояние → картинка широкая, языки пламени крупные, медленные
# Большое X_SCALE (150–300) — LED «прыгают» через шум на большие расстояния → картинка узкая, языки мелкие, «рваные»

# X_SCALE	Ячеек на ленту	Как выглядит
# 60		~0.14			Одна очень широкая волна
# 200		~0.5			Широкая волна с небольшими вариациями
# 400		~1				Один язык пламени на всю ленту
# 800		~2				Два-три языка
# 1500		~3.5			Четыре-пять языков (рекомендуется)
# 3000		~7				Много мелких языков
# ============================================================
X_SCALE      = 60

# ============================================================
# Насколько сдвигается координата t (время) за один кадр

# Разумные значения для 30 fps:

# TIME_STEP	Эффект
# 0.5		Очень медленное, медитативное
# 1			Естественное «дыхание» (рекомендуется)
# 2			Заметное движение, для активного пламени
# 5			Быстрое, «кипящее»
# 10+		Хаотичное, для эффектов «взрыва»
# ============================================================
TIME_STEP    = 1

# ============================================================
# Сколько миллисекунд «спать» между кадрами. Определяет fps: fps = 1000 / FRAME_MS

# Разумные значения:

# FRAME_MS	FPS	Когда использовать
# 50		20	Экономно, для ESP8266 или длинных лент
# 40		25	Компромисс
# 33		30	Баланс (рекомендуется для контражура)
# 20		50	Плавнее, для прямого взгляда
# 16		60	Максимум для глаза
# 5			200	Для «премиум»-плавности (нужен запас CPU)

# Как найти оптимум: поставьте DEBUG_TIMING = True и смотрите на реальный fps в REPL.
# Если вывод показывает fps: 28 при FRAME_MS = 33, значит fill_frame занимает ~2 мс — у вас есть запас,
# можно снизить FRAME_MS до 25 или 20.
# ============================================================
FRAME_MS     = 33

# ============================================================
# Общая яркость ленты в диапазоне 0.0 (выключено) — 1.0 (максимум)

# Про питание: ток потребления ≈ NUM_LEDS × 60 мА × BRIGHTNESS.
# Для 150 LED при BRIGHTNESS = 1.0 — до 9 А! При 0.6 — до 5.4 А.
# Убедитесь, что блок питания справляется с запасом ×1.5.

# Про нагрев: при яркости 1.0 лента и ESP32 заметно греются. При 0.5–0.6 — нагрев минимален.

# Совет: начните с 0.3, добавьте по +0.1, пока не станет «достаточно». Часто оказывается, что 0.5 — уже «ярко».
# ============================================================
BRIGHTNESS   = 0.6

# ============================================================
# Флаг диагностики. Включает/выключает отладочные выводы в REPL

# Периодическая статистика — каждые 2 секунды в REPL:
# [timing] 29.8 fps, кадр 1834 мкс

# Накладные расходы: time.ticks_us() на ESP32 — ~2 мкс на вызов.
# Два вызова на кадр = 4 мкс.
# Для кадра в 33 мс это 0.01% — незаметно.
# ============================================================
DEBUG_TIMING = True